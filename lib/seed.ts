// Deterministic synthetic portfolio, seeded from the CSV dataset in data/demo/ (see its README).
// Hero site S-1001 uses the STRUCTURE of the sponsor's Century Tywood sample plan set; supplier
// documents and ratings are synthetic. After start-up the in-memory store is the only source of truth.
import { createHash } from "crypto";
import { readFileSync } from "fs";
import { basename, join } from "path";
import { loadDocuments, loadFacts, loadProjects, partiesFor } from "./demo-data";
import { compareFacts, materialChanges } from "./intelligence";
import { clockNow } from "./lifecycle/clock";
import { REQUIREMENTS, stageIndex } from "./requirements";
import type { Fact, Release, Revision, ReviewTask, Site } from "./types";

export const TODAY = clockNow(); // system clock unless RELEASEOS_CLOCK is set
const day = 86400000;
const iso = (d: Date) => d.toISOString().slice(0, 10);
export const daysAgo = (n: number) => iso(new Date(TODAY.getTime() - n * day));
export const sha256 = (data: string | Buffer) => createHash("sha256").update(data).digest("hex");

/** Placeholder bytes for seed revisions (no real file). Same content → same hash → reproducible. */
export function placeholderContent(r: Pick<Revision, "siteId" | "requirementId" | "revLabel" | "fileName" | "effectiveDate">) {
  return `SYNTHETIC PLACEHOLDER\nsite=${r.siteId}\ndocument=${r.requirementId}\nrevision=${r.revLabel}\nfile=${r.fileName}\ndate=${r.effectiveDate}\n`;
}

const LABELS = "ABCDEFGHIJ";

function rev(
  siteId: string,
  requirementId: string,
  n: number,
  effectiveDate: string,
  opts: Partial<Revision> = {},
): Revision {
  const revLabel = LABELS[n - 1];
  const fileName = opts.fileName ?? `${requirementId}_rev${revLabel}.pdf`;
  const base = { siteId, requirementId, revLabel, fileName, effectiveDate };
  const status = opts.status ?? "approved";
  return {
    id: `${siteId}-${requirementId}-r${revLabel}`,
    version: n,
    sha256: sha256(placeholderContent(base)),
    source: "seed",
    uploadedBy: "EQORE PM",
    uploadedAt: effectiveDate,
    approvedBy: status === "approved" ? "EQORE engineer" : undefined,
    approvedAt: status === "approved" ? effectiveDate : undefined,
    facts: [],
    engine: "seed",
    synthetic: true,
    ...base,
    ...opts,
    status,
  };
}

export interface SeedData {
  sites: Site[];
  reviews: ReviewTask[];
  releases: Release[];
  files: Map<string, { name: string; mediaType: string; bytes: Buffer; sha256: string }>;
}

/** Real synthetic PDF used as the hero's approved switchgear Rev A (480 VAC). Generated by scripts/generate-sample-pdfs.mjs. */
export const HERO_SWITCHGEAR_A = "SYNTHETIC_Switchgear_Spec_RevA.pdf";
function sampleBytes(name: string) {
  try {
    return readFileSync(join(process.cwd(), "sample-docs", name));
  } catch {
    throw new Error(`Missing sample-docs/${name}. Run: npm run samples`);
  }
}

export function buildSeed(): SeedData {
  const files: SeedData["files"] = new Map();
  const attach = (rel: string) => {
    const bytes = sampleBytes(rel);
    const hash = sha256(bytes);
    const fileId = `f_${hash.slice(0, 24)}`;
    files.set(fileId, { name: basename(rel), mediaType: "application/pdf", bytes, sha256: hash });
    return { fileName: basename(rel), fileId, sha256: hash, mediaType: "application/pdf" };
  };

  // ===== Projects (data/demo/projects.csv) =====
  const sites: Site[] = loadProjects().map((p) => ({
    id: p.id, name: p.name, address: p.address, city: p.city, state: p.state, utility: p.utility, ahj: p.ahj, stage: p.stage,
    chemistry: p.chemistry, powerKw: p.powerKw, energyKwh: p.energyKwh, vendor: p.vendor, inverter: p.inverter,
    location: p.location, disconnectLocation: p.disconnectLocation,
    installDate: p.installDaysAgo !== undefined ? daysAgo(p.installDaysAgo) : undefined,
    documents: [], events: [],
    contacts: partiesFor(p.id).filter((x) => /emergency|24\/7/i.test(x.role)).map((x) => ({ role: x.role, name: x.name, phone: x.phone })),
  }));
  const siteById = (id: string) => {
    const s = sites.find((x) => x.id === id);
    if (!s) throw new Error(`demo dataset: unknown project ${id}`);
    return s;
  };

  // ===== Received documents (data/demo/documents.csv + facts.csv) =====
  const factRows = loadFacts();
  for (const d of loadDocuments()) {
    const facts: Fact[] = factRows
      .filter((x) => x.projectId === d.projectId && x.requirementId === d.requirementId && x.rev === d.rev)
      .map((x) => ({ key: x.key, label: x.label, value: x.value, unit: x.unit, evidence: x.evidence, page: x.page, confidence: 0.9, status: "found", origin: "seed", note: x.evidence ? "Seeded fact — quote copied from the synthetic PDF text" : "Seeded value — no source file on record" }));
    const n = LABELS.indexOf(d.rev) + 1;
    if (n < 1) throw new Error(`documents.csv: unsupported revision label ${d.rev}`);
    siteById(d.projectId).documents.push(rev(d.projectId, d.requirementId, n, daysAgo(d.daysAgo), {
      status: d.status, source: d.source as Revision["source"], uploadedBy: d.uploadedBy, facts, notes: d.note,
      ...(d.file ? attach(d.file) : {}),
    }));
  }

  // ===== Hero site: Century Tywood (structure from sponsor sample plan set) =====
  const H = "S-1001";
  const hero = siteById(H);

  const f = (key: string, label: string, value: string, unit: string | undefined, evidence: string, page: number): Fact => ({ key, label, value, unit, evidence, page, confidence: 0.95 });
  // Facts for the real Rev A PDF: verbatim quotes and pages from its text layer.
  const v = (key: string, label: string, value: string, unit: string | undefined, evidence: string, page: number): Fact => ({ key, label, value, unit, evidence, page, confidence: 0.95, status: "found", evidenceVerified: true, pageVerified: true, origin: "seed" });
  const swBytes = sampleBytes(HERO_SWITCHGEAR_A);
  const swHash = sha256(swBytes);
  const swFileId = `f_${swHash.slice(0, 24)}`;
  files.set(swFileId, { name: HERO_SWITCHGEAR_A, mediaType: "application/pdf", bytes: swBytes, sha256: swHash });
  // Real synthetic PDF bytes for the hero's other AHJ documents (Submission Studio merges actual PDFs).
  const real = (name: string): Partial<Revision> => {
    const bytes = sampleBytes(name);
    const hash = sha256(bytes);
    const fileId = `f_${hash.slice(0, 24)}`;
    files.set(fileId, { name, mediaType: "application/pdf", bytes, sha256: hash });
    return { fileName: name, fileId, sha256: hash, mediaType: "application/pdf", pageCount: (bytes.toString("latin1").match(/\/Type\s*\/Page(?!s)/g) ?? []).length };
  };
  hero.documents = [
    rev(H, "contract", 1, daysAgo(160), { source: "eqore" }),
    rev(H, "proposal", 2, daysAgo(170), { source: "eqore" }),
    // utility_bill intentionally absent: the interconnection package shows a MISSING document blocker.
    rev(H, "site_photos", 1, daysAgo(148), { source: "eqore", fileName: "Revenue Meter + Transformer + MDP + Pole 54.pdf", facts: [f("meter.serial", "Revenue meter serial", "08105663", undefined, "Serial Number: 08105663", 1), f("pole.number", "Utility pole", "54", undefined, "Power Pole Number: 54", 1)] }),
    rev(H, "property_record", 1, daysAgo(148), { source: "eqore", fileName: "79 Lowland Street Map.pdf" }),
    rev(H, "battery_datasheet", 1, daysAgo(120), { source: "supplier", uploadedBy: "Battery supplier", ...real("SYNTHETIC_Battery_Equipment_Summary.pdf"), facts: [f("equipment.model", "Model", "Gotion Edge 760", undefined, "BESS: Gotion Edge 760", 1), f("rating.energy_kwh", "Energy", "760", "kWh", "DC System Size: 760kWh", 1), f("chemistry", "Chemistry", "LFP", undefined, "Lithium iron phosphate", 1)] }),
    rev(H, "inverter_datasheet", 1, daysAgo(118), { source: "supplier", uploadedBy: "Inverter supplier", ...real("SYNTHETIC_Inverter_Equipment_Summary.pdf"), facts: [f("equipment.model", "Model", "Dynapower MPS125", undefined, "Inverter Model: 2 x Dynapower MPS125", 1), f("rating.power_kw", "AC power (each)", "125", "kW", "MPS125 125 kW", 1), f("rating.voltage_v", "AC voltage", "480", "V", "480 VAC 3-phase", 1)] }),
    rev(H, "switchgear_datasheet", 1, daysAgo(115), { source: "supplier", uploadedBy: "Northbridge supplier portal", fileName: HERO_SWITCHGEAR_A, fileId: swFileId, sha256: swHash, mediaType: "application/pdf", pageCount: 2, facts: [
      v("equipment.manufacturer", "Manufacturer", "Northbridge Power Systems", undefined, "Manufacturer: Northbridge Power Systems", 2),
      v("equipment.model", "Model", "NSG-4000", undefined, "Model: NSG-4000", 2),
      v("rating.voltage_v", "Rated voltage (V)", "480", "VAC", "Rated voltage: 480 VAC, 3-phase, 4-wire", 2),
      v("rating.current_a", "Rated current (A)", "400", "A", "Rated continuous current: 400 A", 2),
      v("rating.interrupting_ka", "Interrupting rating (kA)", "65", "kA", "Interrupting rating: 65 kA", 2),
      v("rating.frequency_hz", "Frequency (Hz)", "60", "Hz", "Frequency: 60 Hz", 2),
      v("enclosure.rating", "Enclosure rating", "NEMA 3R", undefined, "Enclosure: NEMA 3R", 2),
      v("equipment.quantity", "Quantity", "1", undefined, "Quantity: 1", 2),
      v("listing.standard", "Listing standard (UL)", "UL 891", undefined, "Listing standard: UL 891", 2),
      v("revision.label", "Revision", "A", undefined, "Revision: A", 1),
      v("doc.date", "Document date", "2026-07-15", undefined, "Date: 2026-07-15", 1),
      v("doc.number", "Document number", "NPS-SG-4000-SPEC", undefined, "Document No.: NPS-SG-4000-SPEC", 1),
    ] }),
    rev(H, "ul9540_listing", 1, daysAgo(112), { source: "supplier", ...real("SYNTHETIC_UL9540_Listing_Placeholder.pdf") }),
    rev(H, "ul9540a_report", 1, daysAgo(112), { source: "supplier", ...real("SYNTHETIC_UL9540A_Report_Placeholder.pdf") }),
    rev(H, "sds", 1, daysAgo(112), { source: "supplier", ...real("SYNTHETIC_SDS_Placeholder.pdf") }),
    rev(H, "plan_set", 1, daysAgo(140), { source: "engineer", status: "approved", fileName: "Full Engineered Plan Set_RevA.pdf" }),
    rev(H, "plan_set", 2, daysAgo(100), { source: "engineer", uploadedBy: "Engineer of record", ...real("SYNTHETIC_Plan_Set_RevB.pdf"), summary: "Rev B: change inverters to 2 × Dynapower MPS125 (per sample plan revision block)", facts: [f("revision.label", "Revision", "B", undefined, "B 01/11/2026 Change inverters to 2 x Dynapower MPS125", 1), f("rating.power_kw", "AC system size", "250", "kW", "AC System Size: 250kW", 1), f("rating.energy_kwh", "DC system size", "760", "kWh", "DC System Size: 760kWh", 1), f("rating.current_a", "Switchgear rating (line diagram)", "400", "A", "400A AC disconnect (ESS-13.0, synthetic)", 2), f("rating.voltage_v", "Switchgear voltage (line diagram)", "480", "VAC", "480 VAC AC disconnect (ESS-13.0, synthetic)", 2)] }),
    rev(H, "ix_application", 1, daysAgo(95), { source: "eqore" }),
    rev(H, "ix_approval", 1, daysAgo(40), { source: "utility", uploadedBy: "Eversource" }),
    // Lifecycle assurance: operations documents prepared ahead of commissioning (synthetic, fictional content).
    rev(H, "om_manual", 1, daysAgo(37), { source: "eqore", uploadedBy: "EQORE operations", ...real("SYNTHETIC_OM_Manual_RevA.pdf") }),
    rev(H, "eop", 1, daysAgo(37), { source: "eqore", uploadedBy: "EQORE operations", ...real("SYNTHETIC_EOP_RevA.pdf") }),
    rev(H, "emergency_info_sheet", 1, daysAgo(37), { source: "eqore", uploadedBy: "EQORE operations", ...real("SYNTHETIC_Emergency_Info_Sheet.pdf") }),
  ];

  const releases: Release[] = [];
  // R1 of the AHJ permit package, built from approved revisions
  const r1Items = ["plan_set", "battery_datasheet", "inverter_datasheet", "switchgear_datasheet", "ul9540_listing", "ul9540a_report", "sds"].map((rid) => {
    const d = hero.documents.filter((x) => x.requirementId === rid && x.status === "approved").sort((a, b) => b.version - a.version)[0];
    return { requirementId: rid, revisionId: d.id, revLabel: d.revLabel, fileName: d.fileName, sha256: d.sha256, approvedBy: d.approvedBy, approvedAt: d.approvedAt };
  });
  const r1: Release = {
    id: `${H}-ahj_permit-R1`,
    siteId: H,
    templateId: "ahj_permit",
    number: 1,
    items: r1Items,
    openFlags: [],
    builtBy: "EQORE engineer",
    builtAt: `${daysAgo(30)}T15:00:00Z`,
    note: "Initial AHJ submission",
    manifestSha256: "",
  };
  r1.manifestSha256 = sha256(JSON.stringify(r1.items));
  releases.push(r1);

  // Second showcase site (operating) for the QR / NFPA 855 lifecycle demo
  const ops = siteById("S-1002");
  ops.documents = REQUIREMENTS.filter((q) => q.stage !== "decommissioning" && q.id !== "training_drill").map((q) =>
    rev(ops.id, q.id, 1, daysAgo(q.recurrenceDays ? (q.id === "ops_record" ? 400 : 200) : 500 - stageIndex(q.stage) * 20), { source: "eqore" }),
  );

  // Every seeded in-review revision gets an open review task, compared against the previous approved revision.
  const reviews: ReviewTask[] = sites.flatMap((s) =>
    s.documents
      .filter((d) => d.status === "in_review")
      .map((d) => {
        const prev = s.documents.filter((x) => x.requirementId === d.requirementId && x.status === "approved" && x.version < d.version).sort((a, b) => b.version - a.version)[0];
        const changes = prev ? compareFacts(prev.facts, d.facts) : [];
        return {
          id: `RV-${d.id}`,
          siteId: s.id,
          revisionId: d.id,
          previousRevisionId: prev?.id,
          requirementId: d.requirementId,
          changes,
          affectedReleaseIds: [],
          affectedRequirementIds: [],
          assignee: "EQORE engineer",
          status: "open" as const,
          createdAt: `${d.uploadedAt}T12:00:00Z`,
          materialChangeCount: materialChanges(changes).length,
        };
      }),
  );
  return { sites, reviews, releases, files };
}
